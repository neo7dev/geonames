"""The deployment's docker-compose.yml: one file, generated from deploy/ and supabase/."""

import yaml

from geonames_server.scripts import deploy_compose
from geonames_server.scripts.deploy_compose import SUPABASE, build, main

SERVICES = {"app", "redis", "db", "auth", "meta", "studio", "kong"}


def _compose() -> dict:
    return yaml.safe_load(build())


class _UniqueKeyLoader(yaml.SafeLoader):
    """Refuses a key given twice in one mapping, as Docker Compose does."""

    def construct_mapping(self, node, deep=False):
        keys = [self.construct_object(key, deep=deep) for key, _ in node.value]
        duplicates = {key for key in keys if keys.count(key) > 1}
        assert not duplicates, f"line {node.start_mark.line + 1}: {duplicates} twice"
        return super().construct_mapping(node, deep=deep)


def test_no_key_is_given_twice():
    yaml.load(build(), Loader=_UniqueKeyLoader)


def test_holds_every_service_and_volume():
    compose = _compose()
    assert set(compose["services"]) == SERVICES
    assert {"redis-data", "app-data", "app-logs", "supabase-db-data"} <= set(
        compose["volumes"]
    )


def test_needs_no_other_file_but_env():
    compose = _compose()
    for name, config in compose["configs"].items():
        assert set(config) == {"content"}, name
    for name, service in compose["services"].items():
        for volume in service.get("volumes", []):
            # Named volumes only: no bind mount of a file from a checkout
            assert not volume.startswith((".", "/")), (name, volume)


def test_config_files_are_inlined_with_dollars_escaped():
    configs = _compose()["configs"]
    for name, file in deploy_compose._CONFIG_ENTRY.findall(
        deploy_compose._sections(SUPABASE.read_text())["configs"]
    ):
        original = (SUPABASE.parent / file).read_text()
        content = configs[name]["content"]
        # Compose turns $$ back into $; a lone $ would be substituted from .env.
        assert content.replace("$$", "").count("$") == 0, name
        assert content.replace("$$", "$") == original, name


def test_services_use_the_inlined_configs():
    services = _compose()["services"]
    assert [c["source"] for c in services["kong"]["configs"]] == [
        "supabase_kong_config",
        "supabase_kong_entrypoint",
    ]
    assert {c["source"] for c in services["db"]["configs"]} == {
        "supabase_db_roles",
        "supabase_db_jwt",
    }


def test_says_it_is_generated():
    assert build().startswith("# GENERATED by `make deploy-compose`")


def test_committed_file_is_up_to_date():
    assert main(["--check"]) == 0
