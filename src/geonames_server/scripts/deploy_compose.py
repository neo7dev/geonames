"""Build the deployment's docker-compose.yml, a single file that needs no checkout.

Fills deploy/docker-compose.template.yml (the app and Redis) with the Supabase
services and volumes from supabase/docker-compose.yml, and turns each of that
file's `configs` (`file: ./kong.yml` and so on) into inline `content`, with `$`
escaped as `$$` so compose does not substitute it. supabase/ stays the one
source: the devcontainer includes it directly.

    python -m geonames_server.scripts.deploy_compose          # write docker-compose.yml
    python -m geonames_server.scripts.deploy_compose --check  # exit 1 if it is out of date

Standard library only.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
TEMPLATE = ROOT / "deploy" / "docker-compose.template.yml"
SUPABASE = ROOT / "supabase" / "docker-compose.yml"
OUTPUT = ROOT / "docker-compose.yml"

_TOP_LEVEL_KEY = re.compile(r"^([a-z_]+):\s*$")
_CONFIG_ENTRY = re.compile(r"^  ([a-z_]+):\n    file: (\S+)$", re.MULTILINE)
_CONTENT_INDENT = " " * 6
_GENERATED = (
    "# GENERATED by `make deploy-compose` from deploy/docker-compose.template.yml and\n"
    "# supabase/. Do not edit: changes here are overwritten.\n\n"
)


def _sections(text: str) -> dict[str, str]:
    """Top-level keys and their bodies, without trailing blank and comment lines."""
    sections: dict[str, list[str]] = {}
    current = None
    for line in text.splitlines():
        match = _TOP_LEVEL_KEY.match(line)
        if match:
            current = match.group(1)
            sections[current] = []
        elif current is not None:
            sections[current].append(line)
    bodies = {}
    for key, lines in sections.items():
        while lines and (not lines[-1].strip() or lines[-1].startswith("#")):
            lines.pop()
        bodies[key] = "\n".join(lines)
    return bodies


def _inline(name: str, path: Path) -> str:
    text = path.read_text()
    if text[:1].isspace():
        raise ValueError(
            f"{path} starts with whitespace, which a YAML block scalar cannot hold"
        )
    lines = [
        _CONTENT_INDENT + line.replace("$", "$$") if line else ""
        for line in text.splitlines()
    ]
    return f"  {name}:\n    content: |\n" + "\n".join(lines)


def build() -> str:
    sections = _sections(SUPABASE.read_text())
    configs = [
        _inline(name, (SUPABASE.parent / file).resolve())
        for name, file in _CONFIG_ENTRY.findall(sections["configs"])
    ]
    if not configs:
        raise ValueError(f"no configs found in {SUPABASE}")

    template = TEMPLATE.read_text()
    # The template's own header explains it; the output says it is generated instead.
    body = template[template.index("# geonames-server deployment") :]
    for marker, value in (
        ("# @supabase-services", sections["services"].strip("\n")),
        ("# @supabase-volumes", sections["volumes"].strip("\n")),
        ("# @supabase-configs", "\n".join(configs)),
    ):
        if body.count(marker) != 1:
            raise ValueError(f"{TEMPLATE} must contain {marker!r} once")
        body = body.replace(marker, value)
    return _GENERATED + body.rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if docker-compose.yml is out of date",
    )
    args = parser.parse_args(argv)

    content = build()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != content:
            print(
                "docker-compose.yml is out of date with deploy/ and supabase/: "
                "run make deploy-compose",
                file=sys.stderr,
            )
            return 1
        return 0
    OUTPUT.write_text(content)
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
